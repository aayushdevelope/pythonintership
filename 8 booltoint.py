# Here we are going to convert an bool to int by using int() function 

x=True
y=False

print(x)
print(y)
print(type(x))
print(type(y))

a=int(x)
print(a)
print(type(a))

b=int(y)
print(b)
print(type(b))

# the bool data type when converted into int data type then the True will store as 1 and False will store as 0




